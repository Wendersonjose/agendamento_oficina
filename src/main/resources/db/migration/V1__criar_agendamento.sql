create table agendamento(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente VARCHAR(150) NOT NULL,
    telefone VARCHAR(20),
    modelo_veiculo VARCHAR(120) NOT NULL,
    placa_veiculo VARCHAR(7) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AGENDADO',
    servico VARCHAR(30) NOT NULL,
    data_hora_agendamento TIMESTAMP NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMP NOT NULL DEFAULT NOW(),
    constraint ck_status CHECK (status IN ( 'AGENDADO', 'CANCELADO','CONCLUIDO' )),
    constraint ck_servico CHECK (servico IN ('CAIXA_DIRECAO',  'BOMBA_DIRECAO'))

);

